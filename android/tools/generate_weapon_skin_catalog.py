"""Generate the reviewed 8.6/8.7 skin allowlist; proprietary inputs stay outside Git.

Usage: python tools/generate_weapon_skin_catalog.py <860-skins.json> <870-skins.json> <localization.json>
Rows are decoded cfg.WeaponUpgrade.WeaponSkin records, not an edited player save.
"""
import argparse
import json
import re
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("legacy", type=Path)
parser.add_argument("current", type=Path)
parser.add_argument("localization", type=Path)
args = parser.parse_args()
legacy = {row["id"]: row for row in json.loads(args.legacy.read_text(encoding="utf-8"))}
rows = json.loads(args.current.read_text(encoding="utf-8"))
assert len(legacy) == 176 and len(rows) == 184
assert len({row["id"] for row in rows}) == len(rows)
assert set(legacy) <= {row["id"] for row in rows}
source = json.loads(args.localization.read_text(encoding="utf-8"))["mSource"]
zh = next(i for i, language in enumerate(source["mLanguages"]) if language["Code"] == "zh-CN")
names = {term["Term"]: term["Languages"][zh] for term in source["mTerms"]}

def literal(text):
    return json.dumps(text, ensure_ascii=False).replace("$", r"\$")

lines = [
    "package com.example.soul_knight_save_editor.unlock", "",
    "data class WeaponSkinDefinition(val weapon: String, val index: Int, val id: String,",
    "    val label: String, val rarity: Int, val weaponLabel: String, val sinceVersion: Int)", "",
    "/** Reviewed cfg.WeaponUpgrade.WeaponSkin rows; rarity and index are independent fields.",
    " * 176 skins in 8.6; 184 in 8.7. Localized names alone never extend this allowlist.",
    " * Generated by android/tools/generate_weapon_skin_catalog.py. */",
    "object WeaponSkinCatalog {",
    "    val supportedVersions = setOf(80600, 80700)",
    "    val entries = listOf(",
]
for row in sorted(rows, key=lambda value: (value["weapon"], value["index"])):
    assert re.fullmatch(r"weapon_[A-Za-z0-9_]+", row["weapon"])
    assert isinstance(row["index"], int) and row["index"] > 0
    assert row["id"] == f'{row["weapon"]}_s_{row["index"]}'
    assert row["rarity"] in (1, 2, 3, 4) and names.get(row["id"])
    if row["id"] in legacy:
        assert all(row[key] == legacy[row["id"]][key] for key in ("weapon", "index", "rarity"))
    version = 80600 if row["id"] in legacy else 80700
    weapon_name = names.get("weapon/" + row["weapon"]) or row["extra"]
    lines.append(f'        WeaponSkinDefinition({literal(row["weapon"])}, {row["index"]}, {literal(row["id"])}, '
                 f'{literal(names[row["id"]])}, {row["rarity"]}, {literal(weapon_name)}, {version}),')
lines += ["    )", "    fun forVersion(version: Int): List<WeaponSkinDefinition> {",
          '        require(version in supportedVersions) { "武器皮肤目录仅核对了 8.6.0 / 8.7.0" }',
          "        return entries.filter { it.sinceVersion <= version }", "    }", "}", ""]
target = Path(__file__).resolve().parents[1] / "app/src/main/java/com/example/soul_knight_save_editor/unlock/WeaponSkinCatalog.kt"
target.write_text("\n".join(lines), encoding="utf-8")
print(f"Generated {len(rows)} reviewed skin definitions")
