"""Generate reviewed weapon names from the extracted 8.6.0 localization MonoBehaviour.

Usage: python tools/generate_weapon_catalog.py <extracted-localization.json>
The proprietary asset dump stays outside the repository.
"""
import argparse
import json
import re
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("localization_json", type=Path)
args = parser.parse_args()
source = json.loads(args.localization_json.read_text(encoding="utf-8"))["mSource"]
language = next(i for i, entry in enumerate(source["mLanguages"]) if entry["Code"] == "zh-CN")
names = {}
for term in source["mTerms"]:
    match = re.fullmatch(r"weapon/(weapon_\d+)", term["Term"])
    if match:
        assert match[1] not in names and term["Languages"][language]
        names[match[1]] = term["Languages"][language]
assert len(names) == 416, "Expected the reviewed 416 numbered weapons."
# Community omissions independently confirmed in both versions' zh-CN resources.
# Other non-numbered terms also describe skills/rooms and are not auto-added.
reviewed_named = {
    "weapon_hammerhead": "锤头鲨",
    "weapon_lighter": "遗迹火焰法杖",
    "weapon_void_hand": "手骨回旋镖",
}
terms = {term["Term"]: term["Languages"][language] for term in source["mTerms"]}
for key, name in reviewed_named.items():
    assert terms.get(f"weapon/{key}") == name, f"Unconfirmed weapon: {key}"

def literal(text):
    return json.dumps(text, ensure_ascii=False).replace("$", r"\$")

lines = [
    "package com.example.soul_knight_save_editor.unlock", "",
    "/** 416 numbered IDs from 8.6.0 localization.ab zh-CN weapon/weapon_<digits> terms.",
    " * Resource SHA-256: dfa5677a2f9504fcce93c8da5c5b20063282dfe31a90caae92828dba257d6722",
    " * Plus three reviewed named IDs, confirmed in both 8.6.0 and 8.7.0 resources.",
    " * No guessed ID ranges. Other existing non-numbered counters are handled separately.",
    " * Generated by android/tools/generate_weapon_catalog.py. */",
    "object WeaponCatalog {",
    '    private val idPattern = Regex("^weapon_[a-zA-Z0-9_]+$")',
    "    fun isWeaponId(id: String) = idPattern.matches(id)",
    "    val names: Map<String, String> = linkedMapOf(",
]
lines += [f"        {literal(key)} to {literal(names[key])}," for key in sorted(names, key=lambda value: int(value[7:]))]
lines += [f"        {literal(key)} to {literal(name)}," for key, name in reviewed_named.items()]
lines += ["    )", "}", ""]
target = Path(__file__).resolve().parents[1] / "app/src/main/java/com/example/soul_knight_save_editor/unlock/WeaponCatalog.kt"
target.write_text("\n".join(lines), encoding="utf-8")
print(f"Generated {len(names) + len(reviewed_named)} weapon names: {target}")
